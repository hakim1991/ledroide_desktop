for (const w of list(ADJ4)) { accepted.add(w + 'E'); accepted.add(w + 'S') }
for (const v of list(VERBS_ER)) for (const w of verbForms(v, 'er')) accepted.add(w)
for (const v of list(VERBS_IR)) for (const w of verbForms(v, 'ir')) accepted.add(w)
for (const v of list(VERBS_RE)) for (const w of verbForms(v, 're')) accepted.add(w)
for (const w of accepted) if (!FIVE.test(w)) accepted.delete(w)

