const list = (s) => s.split(/\s+/).filter(Boolean)
const FIVE = /^[A-Z]{5}$/

function verbForms(raw, group) {
  const intrans = raw.endsWith('*')
  const v = raw.replace('*', '')
  const stem = v.slice(0, -2)
  let ends
  if (group === 'er') {
    const soft = stem.endsWith('G')
    ends = ['ER', 'EZ', 'ES', 'AI', 'AS', 'AT', 'E', 'A', 'ENT', 'ONS', 'AIS', 'AIT', 'ANT', 'ERA']
    if (!intrans) ends.push('EE', 'EES')
    if (soft) ends = ends.filter((e) => !/^[AO]/.test(e))
  } else if (group === 'ir') {
    ends = ['IR', 'IS', 'IT', 'I']
    if (!intrans) ends.push('IE')
  } else {
    ends = ['U', 'S', 'E']
  }
  return ends.map((e) => stem + e).filter((w) => FIVE.test(w))
}

